CREATE TABLE family
(
    family_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id            BIGINT NOT NULL,
    name                VARCHAR(20) NOT NULL,
    invite_code         VARCHAR(6),
    invite_token        VARCHAR(64),
    invite_expires_at   TIMESTAMP,
    region_code         VARCHAR(10),
    latitude            DECIMAL(10, 7),
    longitude           DECIMAL(10, 7),
    address             VARCHAR(255),
    created_at          TIMESTAMP NOT NULL DEFAULT now(),
    updated_at          TIMESTAMP,
    CONSTRAINT uk_family_owner UNIQUE (owner_id),
    CONSTRAINT uk_family_name UNIQUE (name),
    CONSTRAINT uk_family_invite_code UNIQUE (invite_code),
    CONSTRAINT uk_family_invite_token UNIQUE (invite_token),
    CONSTRAINT fk_family_owner FOREIGN KEY (owner_id) REFERENCES member (member_id)
);