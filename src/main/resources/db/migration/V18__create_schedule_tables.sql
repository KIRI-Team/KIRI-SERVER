CREATE TABLE schedule
(
    schedule_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id       BIGINT       NOT NULL,
    bucket_item_id  BIGINT,
    proposer_id     BIGINT,
    schedule_date   DATE,
    schedule_time   TIME,
    request_message VARCHAR(100),
    status          VARCHAR(20)  NOT NULL DEFAULT 'PENDING_RESPONSE',
    started_at      TIMESTAMPTZ,
    completed_at    TIMESTAMPTZ,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ,
    CONSTRAINT ck_schedule_status CHECK (status IN ('PENDING_RESPONSE', 'CONFIRMED', 'NOT_CONFIRMED', 'CANCELLED', 'COMPLETED')),
    CONSTRAINT fk_schedule_family FOREIGN KEY (family_id) REFERENCES family (family_id) ON DELETE CASCADE,
    CONSTRAINT fk_schedule_proposer FOREIGN KEY (proposer_id) REFERENCES member (member_id) ON DELETE SET NULL
);

CREATE INDEX idx_schedule_family_date ON schedule (family_id, schedule_date);

CREATE TABLE schedule_participant
(
    schedule_participant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id             BIGINT      NOT NULL,
    member_id               BIGINT,
    status                  VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    is_reconfirm_required   BOOLEAN     NOT NULL DEFAULT FALSE,
    responded_at            TIMESTAMPTZ,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ,
    CONSTRAINT uk_schedule_participant UNIQUE (schedule_id, member_id),
    CONSTRAINT ck_schedule_participant_status CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED')),
    CONSTRAINT fk_schedule_participant_schedule FOREIGN KEY (schedule_id) REFERENCES schedule (schedule_id) ON DELETE CASCADE,
    CONSTRAINT fk_schedule_participant_member FOREIGN KEY (member_id) REFERENCES member (member_id) ON DELETE SET NULL
);

CREATE INDEX idx_schedule_participant_member ON schedule_participant (member_id);
