CREATE TABLE notification
(
    notification_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id           BIGINT       NOT NULL,
    notification_type   VARCHAR(25)  NOT NULL,
    title               VARCHAR(100) NOT NULL,
    body                VARCHAR(255) NOT NULL,
    sent_at             TIMESTAMP,
    status              VARCHAR(25)  NOT NULL,
    processing_at       TIMESTAMP,
    processing_lease_id UUID,
    created_at          TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at          TIMESTAMP             DEFAULT now(),
    CONSTRAINT fk_notification_member FOREIGN KEY (member_id) REFERENCES member (member_id)
);