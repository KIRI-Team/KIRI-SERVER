CREATE TABLE bucket_item
(
    bucket_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id      BIGINT      NOT NULL,
    member_id      BIGINT,
    mission_id     BIGINT      NOT NULL,
    status         VARCHAR(20) NOT NULL DEFAULT 'SAVED',
    saved_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at   TIMESTAMPTZ,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ,
    CONSTRAINT ck_bucket_item_status CHECK (status IN ('SAVED', 'SCHEDULED', 'COMPLETED')),
    CONSTRAINT fk_bucket_item_family FOREIGN KEY (family_id) REFERENCES family (family_id) ON DELETE CASCADE,
    CONSTRAINT fk_bucket_item_member FOREIGN KEY (member_id) REFERENCES member (member_id) ON DELETE SET NULL,
    CONSTRAINT fk_bucket_item_mission FOREIGN KEY (mission_id) REFERENCES mission (mission_id)
);

-- COMPLETED 이후에는 같은 미션을 다시 저장할 수 있어 SAVED·SCHEDULED만 유일하게 제한
CREATE UNIQUE INDEX uk_bucket_item_active ON bucket_item (member_id, mission_id) WHERE status IN ('SAVED', 'SCHEDULED');
CREATE INDEX idx_bucket_item_family_id ON bucket_item (family_id);
