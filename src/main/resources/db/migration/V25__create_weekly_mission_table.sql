CREATE TABLE weekly_mission (
    weekly_mission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id BIGINT NOT NULL,
    mission_id BIGINT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,

    CONSTRAINT fk_weekly_mission_family FOREIGN KEY (family_id) REFERENCES family (family_id) ON DELETE CASCADE,
    CONSTRAINT fk_weekly_mission_mission FOREIGN KEY (mission_id) REFERENCES mission (mission_id),
    CONSTRAINT uk_weekly_mission_family_week UNIQUE (family_id, start_date)
);

ALTER TABLE bucket_item
    ADD COLUMN weekly_mission_id BIGINT,
    ADD CONSTRAINT fk_bucket_item_weekly_mission FOREIGN KEY (weekly_mission_id) REFERENCES weekly_mission (weekly_mission_id);
