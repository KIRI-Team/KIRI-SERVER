CREATE TABLE admin
(
    admin_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id           VARCHAR(50)  NOT NULL,
    password_hash      VARCHAR(100) NOT NULL,
    name               VARCHAR(50)  NOT NULL,
    enabled            BOOLEAN      NOT NULL DEFAULT TRUE,
    refresh_token_hash VARCHAR(64),
    last_login_at      TIMESTAMPTZ,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ,
    CONSTRAINT uk_admin_login_id UNIQUE (login_id)
);

CREATE TABLE admin_audit_log
(
    admin_audit_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id           BIGINT      NOT NULL,
    action             VARCHAR(30) NOT NULL,
    target_type        VARCHAR(30) NOT NULL,
    target_id          BIGINT,
    reason             VARCHAR(500),
    before_data        JSONB,
    after_data         JSONB,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ,
    CONSTRAINT fk_admin_audit_log_admin FOREIGN KEY (admin_id) REFERENCES admin (admin_id)
);

CREATE INDEX idx_admin_audit_log_target ON admin_audit_log (target_type, target_id);
CREATE INDEX idx_admin_audit_log_admin_created ON admin_audit_log (admin_id, created_at);
CREATE INDEX idx_admin_audit_log_created ON admin_audit_log (created_at);
