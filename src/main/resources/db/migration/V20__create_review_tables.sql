CREATE TABLE review (
    review_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id             BIGINT       NOT NULL,
    schedule_participant_id BIGINT       NOT NULL,
    content                 VARCHAR(500) NOT NULL,
    star_rating             SMALLINT     NOT NULL,
    is_rejoin_intended      BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ,
    CONSTRAINT fk_review_schedule FOREIGN KEY (schedule_id) REFERENCES schedule (schedule_id),
    CONSTRAINT fk_review_schedule_participant FOREIGN KEY (schedule_participant_id) REFERENCES schedule_participant (schedule_participant_id),
    CONSTRAINT uk_review_schedule UNIQUE (schedule_id, schedule_participant_id)
);

CREATE TABLE review_photo (
    review_photo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id       BIGINT       NOT NULL,
    image_key       VARCHAR(500) NOT NULL,
    display_order   SMALLINT     NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ,
    CONSTRAINT fk_review_photo_review FOREIGN KEY (review_id) REFERENCES review (review_id)
);