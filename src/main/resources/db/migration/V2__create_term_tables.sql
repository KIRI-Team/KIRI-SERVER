-- 약관
CREATE TABLE term
(
    term_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             VARCHAR(50)  NOT NULL,
    short_description VARCHAR(100) NOT NULL,
    description       TEXT         NOT NULL,
    is_required       BOOLEAN      NOT NULL DEFAULT FALSE,
    version           INTEGER      NOT NULL DEFAULT 1,
    created_at        TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at        TIMESTAMP             DEFAULT now()
);

-- 사용자 약관
CREATE TABLE member_term
(
    member_term_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_id        BIGINT    NOT NULL,
    member_id      BIGINT    NOT NULL,
    term_version   INTEGER   NOT NULL,
    agreed_at      TIMESTAMP,
    created_at     TIMESTAMP NOT NULL DEFAULT now(),
    updated_at     TIMESTAMP          DEFAULT now(),
    CONSTRAINT uk_member_term UNIQUE (member_id, term_id),
    CONSTRAINT fk_member_term_term FOREIGN KEY (term_id) REFERENCES term (term_id),
    CONSTRAINT fk_member_term_member FOREIGN KEY (member_id) REFERENCES member (member_id)
);
