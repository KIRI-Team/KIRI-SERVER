-- 검수 대기 시작 시각. 대기시간 계산에 쓴다.
ALTER TABLE external_record ADD COLUMN review_requested_at TIMESTAMPTZ;
UPDATE external_record
   SET review_requested_at = COALESCE(updated_at, created_at)
 WHERE process_status = 'REVIEW_REQUIRED';

-- 검수 업무 상태. 원본 처리 상태(external_record.process_status), 미션 공개 상태(mission.status)와 따로 관리한다.
CREATE TABLE mission_review_task
(
    mission_review_task_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_record_id     BIGINT      NOT NULL,
    status                 VARCHAR(20) NOT NULL,
    assignee_admin_id      BIGINT,
    review_reason          VARCHAR(20),
    note                   VARCHAR(500),
    applied_overrides      JSONB,
    resolved_by            BIGINT,
    resolved_at            TIMESTAMPTZ,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ,
    CONSTRAINT ck_mission_review_task_status CHECK (status IN ('OPEN', 'ON_HOLD', 'APPROVED', 'REJECTED')),
    CONSTRAINT fk_mission_review_task_record FOREIGN KEY (external_record_id) REFERENCES external_record (external_record_id),
    CONSTRAINT fk_mission_review_task_assignee FOREIGN KEY (assignee_admin_id) REFERENCES admin (admin_id),
    CONSTRAINT fk_mission_review_task_resolver FOREIGN KEY (resolved_by) REFERENCES admin (admin_id)
);

-- 레코드당 열린 작업은 하나뿐이다.
CREATE UNIQUE INDEX uk_mission_review_task_open ON mission_review_task (external_record_id)
    WHERE status IN ('OPEN', 'ON_HOLD');
CREATE INDEX idx_mission_review_task_record ON mission_review_task (external_record_id);

