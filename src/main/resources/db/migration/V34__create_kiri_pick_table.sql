-- 끼리 픽: 운영자가 고른 공통 큐레이션. 앱 미션 목록 첫 페이지 상단에 노출한다.
CREATE TABLE kiri_pick
(
    kiri_pick_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mission_id    BIGINT       NOT NULL,
    headline      VARCHAR(100) NOT NULL,
    description   VARCHAR(500),
    image_url     VARCHAR(500),
    display_order INTEGER      NOT NULL DEFAULT 0,
    start_at      TIMESTAMPTZ  NOT NULL,
    end_at        TIMESTAMPTZ  NOT NULL,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    pick_type     VARCHAR(20)  NOT NULL DEFAULT 'CURATION',
    partner_name  VARCHAR(100),
    created_by    BIGINT,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ,
    CONSTRAINT ck_kiri_pick_type CHECK (pick_type IN ('CURATION', 'COLLABORATION', 'PAID')),
    CONSTRAINT ck_kiri_pick_period CHECK (end_at > start_at),
    CONSTRAINT fk_kiri_pick_mission FOREIGN KEY (mission_id) REFERENCES mission (mission_id),
    CONSTRAINT fk_kiri_pick_created_by FOREIGN KEY (created_by) REFERENCES admin (admin_id)
);

CREATE INDEX idx_kiri_pick_window ON kiri_pick (active, start_at, end_at);
CREATE INDEX idx_kiri_pick_mission ON kiri_pick (mission_id);

-- 버킷이 어느 끼리 픽에서 저장됐는지. 일정·완료 성과는 이 버킷 하나를 통해 한 픽에만 귀속된다.
ALTER TABLE bucket_item ADD COLUMN source_kiri_pick_id BIGINT;
ALTER TABLE bucket_item
    ADD CONSTRAINT fk_bucket_item_kiri_pick FOREIGN KEY (source_kiri_pick_id) REFERENCES kiri_pick (kiri_pick_id);
CREATE INDEX idx_bucket_item_kiri_pick ON bucket_item (source_kiri_pick_id) WHERE source_kiri_pick_id IS NOT NULL;
