CREATE TABLE schedule_condition
(
    schedule_condition_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id           BIGINT      NOT NULL,
    condition_type        VARCHAR(20) NOT NULL,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ,
    CONSTRAINT uk_schedule_condition UNIQUE (schedule_id, condition_type),
    CONSTRAINT ck_schedule_condition_type CHECK (condition_type IN ('REDUCE_STEPS', 'MORE_REST', 'LOWER_BUDGET', 'AVOID_CROWD')),
    CONSTRAINT fk_schedule_condition_schedule FOREIGN KEY (schedule_id) REFERENCES schedule (schedule_id) ON DELETE CASCADE
);
