-- 앱 행동 이벤트(노출·클릭·화면 이탈 등). 서버에 이미 남는 성공 기록(버킷·일정·리뷰)은 넣지 않는다.
CREATE TABLE app_event
(
    app_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     VARCHAR(64) NOT NULL,
    member_id    BIGINT,
    family_id    BIGINT,
    event_name   VARCHAR(50) NOT NULL,
    properties   JSONB,
    platform     VARCHAR(20),
    app_version  VARCHAR(20),
    occurred_at  TIMESTAMPTZ NOT NULL,
    received_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- 클라이언트 재전송 중복 방지
    CONSTRAINT uk_app_event_event_id UNIQUE (event_id)
);

CREATE INDEX idx_app_event_name_occurred ON app_event (event_name, occurred_at);
CREATE INDEX idx_app_event_member_occurred ON app_event (member_id, occurred_at);
