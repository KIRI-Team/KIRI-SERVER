-- 사용자 (ERD 기준 전체 컬럼)
-- family_id: family 테이블 생성 시 FK 제약 추가 예정
CREATE TABLE member
(
    member_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id           BIGINT,
    nickname            VARCHAR(20),
    social_provider     VARCHAR(20),
    social_provider_uid VARCHAR(255),
    gender              VARCHAR(20),
    birth_date          DATE,
    email               VARCHAR(255),
    family_role         VARCHAR(20),
    last_access_at      TIMESTAMP,
    created_at          TIMESTAMP NOT NULL DEFAULT now(),
    updated_at          TIMESTAMP
);
