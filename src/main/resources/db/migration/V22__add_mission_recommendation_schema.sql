ALTER TABLE member_answer
    ADD COLUMN indoor_outdoor VARCHAR(20),
    ADD COLUMN duration_level VARCHAR(20),
    ADD COLUMN price_level VARCHAR(20),
    ADD COLUMN activity_level VARCHAR(20);

CREATE TABLE member_answer_category (
    member_answer_category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_answer_id BIGINT NOT NULL,
    category VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_member_answer_category_member_answer FOREIGN KEY (member_answer_id) REFERENCES member_answer (member_answer_id) ON DELETE CASCADE,
    CONSTRAINT uk_member_answer_category UNIQUE (member_answer_id, category)
);

CREATE TABLE family_mission_recommendation (
    family_mission_recommendation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id BIGINT NOT NULL,
    mission_id BIGINT NOT NULL,
    recommendation_score DECIMAL(12, 10) NOT NULL,
    recommendation_rank INTEGER NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_family_mission_recommendation_family FOREIGN KEY (family_id) REFERENCES family (family_id),
    CONSTRAINT fk_family_mission_recommendation_mission FOREIGN KEY (mission_id) REFERENCES mission (mission_id),
    CONSTRAINT uk_family_mission_recommendation_family_mission UNIQUE (family_id, mission_id)
);