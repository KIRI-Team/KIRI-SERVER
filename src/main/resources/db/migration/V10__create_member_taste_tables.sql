CREATE TABLE member_taste
(
    member_taste_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id       BIGINT      NOT NULL,
    indoor_outdoor  VARCHAR(20),
    activity_level  VARCHAR(20) NOT NULL,
    price_level     VARCHAR(20),
    duration_level  VARCHAR(20),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ,
    CONSTRAINT uk_member_taste_member UNIQUE (member_id),
    CONSTRAINT ck_member_taste_indoor_outdoor CHECK (indoor_outdoor IN ('INDOOR', 'OUTDOOR')),
    CONSTRAINT fk_member_taste_member FOREIGN KEY (member_id) REFERENCES member (member_id)
);

CREATE TABLE member_taste_category
(
    member_taste_category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_taste_id          BIGINT      NOT NULL,
    category                 VARCHAR(20) NOT NULL,
    created_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at               TIMESTAMPTZ,
    CONSTRAINT uk_member_taste_category UNIQUE (member_taste_id, category),
    CONSTRAINT fk_member_taste_category_taste FOREIGN KEY (member_taste_id)
        REFERENCES member_taste (member_taste_id) ON DELETE CASCADE
);
