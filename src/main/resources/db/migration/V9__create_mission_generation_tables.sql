CREATE TABLE place
(
    place_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100)   NOT NULL,
    place_type   VARCHAR(20)    NOT NULL,
    region_code  VARCHAR(10),
    latitude     DECIMAL(10, 7) NOT NULL,
    longitude    DECIMAL(10, 7) NOT NULL,
    address      VARCHAR(255),
    opening_time TIME,
    closing_time TIME,
    image_url    VARCHAR(500),
    image_source VARCHAR(255),
    created_at   TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ
);

CREATE INDEX idx_place_name ON place (name);
CREATE INDEX idx_place_location ON place (latitude, longitude);

CREATE TABLE mission
(
    mission_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id              BIGINT       NOT NULL,
    title                 VARCHAR(100) NOT NULL,
    description           TEXT         NOT NULL,
    category              VARCHAR(20)  NOT NULL,
    mission_type          VARCHAR(20)  NOT NULL,
    status                VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    image_url             VARCHAR(500),
    image_source          VARCHAR(255),
    duration_min_minutes  INTEGER,
    duration_max_minutes  INTEGER,
    price                 INTEGER,
    estimated_steps_min   INTEGER,
    estimated_steps_max   INTEGER,
    indoor_outdoor        VARCHAR(20),
    start_date            DATE,
    end_date              DATE,
    recommendation_reason VARCHAR(255),
    opening_time          TIME,
    closing_time          TIME,
    title_edited          BOOLEAN      NOT NULL DEFAULT FALSE,
    checklist_edited      BOOLEAN      NOT NULL DEFAULT FALSE,
    cancel_source         VARCHAR(20),
    cancel_reason         VARCHAR(255),
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ,
    CONSTRAINT fk_mission_place FOREIGN KEY (place_id) REFERENCES place (place_id)
);

CREATE INDEX idx_mission_place_id ON mission (place_id);
CREATE INDEX idx_mission_status_category ON mission (status, category);
CREATE INDEX idx_mission_title ON mission (title);

CREATE TABLE mission_checklist_item
(
    mission_checklist_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mission_id                BIGINT       NOT NULL,
    item_type                 VARCHAR(20)  NOT NULL,
    source                    VARCHAR(20)  NOT NULL DEFAULT 'ORIGIN',
    title                     VARCHAR(100) NOT NULL,
    description               VARCHAR(255),
    display_order             INTEGER      NOT NULL DEFAULT 1,
    created_at                TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at                TIMESTAMPTZ,
    CONSTRAINT uk_mission_checklist_item_order UNIQUE (mission_id, item_type, display_order),
    CONSTRAINT fk_mission_checklist_item_mission FOREIGN KEY (mission_id) REFERENCES mission (mission_id)
);

CREATE TABLE external_record
(
    external_record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id           BIGINT,
    mission_id         BIGINT,
    external_source    VARCHAR(20)  NOT NULL,
    external_id        VARCHAR(100) NOT NULL,
    source_url         VARCHAR(500),
    process_status     VARCHAR(20)  NOT NULL,
    review_reason      VARCHAR(20),
    raw_data           JSONB,
    content_hash       VARCHAR(64)  NOT NULL,
    origin_modified_at TIMESTAMPTZ,
    synced_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    missing_count      INTEGER      NOT NULL DEFAULT 0,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ,
    CONSTRAINT uk_external_record_source_id UNIQUE (external_source, external_id),
    CONSTRAINT fk_external_record_place FOREIGN KEY (place_id) REFERENCES place (place_id),
    CONSTRAINT fk_external_record_mission FOREIGN KEY (mission_id) REFERENCES mission (mission_id)
);

CREATE INDEX idx_external_record_mission_id ON external_record (mission_id);
CREATE INDEX idx_external_record_process_status ON external_record (process_status);

CREATE TABLE external_record_history
(
    external_record_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_record_id         BIGINT      NOT NULL,
    raw_data                   JSONB       NOT NULL,
    content_hash               VARCHAR(64) NOT NULL,
    created_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at                 TIMESTAMPTZ,
    CONSTRAINT fk_external_record_history_external_record
        FOREIGN KEY (external_record_id) REFERENCES external_record (external_record_id)
);

CREATE INDEX idx_external_record_history_external_record_id ON external_record_history (external_record_id);

CREATE TABLE external_sync_state
(
    external_sync_state_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_source        VARCHAR(20) NOT NULL,
    last_cursor            VARCHAR(255),
    last_success_at        TIMESTAMPTZ,
    last_status            VARCHAR(20),
    last_error_code        VARCHAR(30),
    last_error             VARCHAR(500),
    window_full            BOOLEAN     NOT NULL DEFAULT FALSE,
    window_end_date        DATE,
    progress_date          DATE,
    progress_page          INTEGER,
    daily_call_date        DATE,
    daily_call_count       INTEGER     NOT NULL DEFAULT 0,
    running_since          TIMESTAMPTZ,
    last_full_check_at     TIMESTAMPTZ,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ,
    CONSTRAINT uk_external_sync_state_source UNIQUE (external_source)
);

CREATE TABLE external_sync_retry
(
    external_sync_retry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_source        VARCHAR(20)  NOT NULL,
    external_id            VARCHAR(100) NOT NULL,
    raw_item               JSONB        NOT NULL,
    attempt_count          INTEGER      NOT NULL DEFAULT 0,
    last_error             VARCHAR(500),
    created_at             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ,
    CONSTRAINT uk_external_sync_retry_source_id UNIQUE (external_source, external_id)
);
