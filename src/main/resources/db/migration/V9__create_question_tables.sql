-- 질문 (전체 가족이 공유하는 질문 풀)
-- fixed_day: 1~7이면 N일차 고정 질문, NULL이면 랜덤 질문
-- PostgreSQL UNIQUE는 NULL끼리 중복으로 보지 않아서 NULL은 여러 개 허용된다.
CREATE TABLE question
(
    question_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content     VARCHAR(255) NOT NULL,
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    fixed_day   INTEGER,
    created_at  TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at  TIMESTAMP,
    CONSTRAINT uk_question_fixed_day UNIQUE (fixed_day)
);

-- 가족별 배정 질문
CREATE TABLE family_question
(
    family_question_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_date      DATE      NOT NULL,
    question_id        BIGINT    NOT NULL,
    family_id          BIGINT    NOT NULL,
    created_at         TIMESTAMP NOT NULL DEFAULT now(),
    updated_at         TIMESTAMP,
    CONSTRAINT uk_family_question_question UNIQUE (family_id, question_id),
    CONSTRAINT uk_family_question_date UNIQUE (family_id, question_date),
    CONSTRAINT fk_family_question_question FOREIGN KEY (question_id) REFERENCES question (question_id),
    CONSTRAINT fk_family_question_family FOREIGN KEY (family_id) REFERENCES family (family_id)
);

-- 회원 답변 (행이 있으면 답변한 것)
CREATE TABLE member_answer
(
    member_answer_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content            VARCHAR(500) NOT NULL,
    family_question_id BIGINT       NOT NULL,
    member_id          BIGINT       NOT NULL,
    created_at         TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at         TIMESTAMP,
    CONSTRAINT uk_member_answer UNIQUE (member_id, family_question_id),
    CONSTRAINT fk_member_answer_family_question FOREIGN KEY (family_question_id) REFERENCES family_question (family_question_id),
    CONSTRAINT fk_member_answer_member FOREIGN KEY (member_id) REFERENCES member (member_id)
);

-- 찌르기 (같은 사람에게 하루 1회)
CREATE TABLE poke
(
    poke_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poke_date   DATE      NOT NULL,
    sender_id   BIGINT    NOT NULL,
    receiver_id BIGINT    NOT NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT now(),
    updated_at  TIMESTAMP,
    CONSTRAINT uk_poke_sender_receiver_date UNIQUE (sender_id, receiver_id, poke_date),
    CONSTRAINT fk_poke_sender FOREIGN KEY (sender_id) REFERENCES member (member_id),
    CONSTRAINT fk_poke_receiver FOREIGN KEY (receiver_id) REFERENCES member (member_id)
);
